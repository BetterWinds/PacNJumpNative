#!/usr/bin/env python3
"""Writes core/pnj_maps_data.h (git-ignored) with the 42 hand-made maps compiled in, for the personal/parity build.

    python tools/gen_maps.py game.apk          reads res/raw/*.map from your own copy of the original APK
    python tools/gen_maps.py maps.json         or the web version's assets/maps.json

Without that file the engine builds with no maps and loads them from pnj.pack at runtime (the normal, shareable setup).
"""
import json, sys, zipfile
src = sys.argv[1] if len(sys.argv) > 1 else '../web/assets/maps.json'
if src.lower().endswith('.apk'):
    z = zipfile.ZipFile(src)
    m = {n[8:-4]: list(z.read(n)) for n in sorted(z.namelist()) if n.startswith('res/raw/') and n.endswith('.map')}
else:
    m = json.load(open(src))
names = list(m.keys())
out = ['/* generated by tools/gen_maps.py (hand-made chunk maps, 24 rows x 16 cells). Do not edit, do not commit. */']
for n in names:
    out.append('static const uint8_t pnj_map_%s[%d] = {%s};' % (n, len(m[n]), ','.join(str(int(v)) for v in m[n])))
out.append('static const pnj_map PNJ_MAPS[] = {')
for n in names: out.append('    { "%s", %d, pnj_map_%s },' % (n, len(m[n]), n))
out += ['};', '#define PNJ_NMAPS %d' % len(names)]
open('core/pnj_maps_data.h', 'w').write('\n'.join(out) + '\n')
print('wrote core/pnj_maps_data.h with %d maps' % len(names))
